/**
 * Bridge-level provenance tag for Sessions created through MCP.
 *
 * This is deliberately NOT the Host `origin` field: `origin: 'subagent'` is
 * Host semantics owned by the Session Controller. `source` is a purely
 * bridge-local annotation so an MCP client can tell which of its own Sessions
 * were created by which caller.
 *
 * The registry is in-process and in-memory only: a host restart loses it, and
 * unrecorded Sessions report no source rather than a guessed one.
 */

/** Default source for callers that do not pass one. */
export const DEFAULT_SOURCE = "mcp";

/** Maximum accepted length of a source tag. */
export const SOURCE_MAX_LENGTH = 64;

const SOURCE_PATTERN = /^[a-z0-9._-]+$/;

export class SourceValidationError extends Error {
  constructor(message) {
    super(message);
    this.name = "SourceValidationError";
  }
}

/**
 * Validate a caller-supplied source tag: non-empty, at most 64 characters,
 * restricted to lowercase alphanumerics plus `.`, `_` and `-`.
 *
 * The charset keeps the tag safe to embed in a Session title and in log lines
 * without escaping, so arbitrary caller text can never reach either.
 */
export function normalizeSource(value) {
  if (value === undefined) return DEFAULT_SOURCE;
  if (typeof value !== "string") throw new SourceValidationError("source must be a string");
  if (value.length === 0) throw new SourceValidationError("source must be a non-empty string");
  if (value.length > SOURCE_MAX_LENGTH) {
    throw new SourceValidationError(`source exceeds ${SOURCE_MAX_LENGTH} characters`);
  }
  if (!SOURCE_PATTERN.test(value)) {
    throw new SourceValidationError("source may only contain [a-z0-9._-]");
  }
  return value;
}

/**
 * Build the automatic title applied when a caller created a Session through
 * MCP without supplying a title, so a human scanning the DSH sidebar can see
 * the Session is machine-driven and which caller owns it.
 *
 * @param source - validated source tag.
 * @param sessionId - Host session id (already generated by the Host).
 */
export function defaultSessionTitle(source, sessionId) {
  const tail = typeof sessionId === "string" ? sessionId.slice(-8) : "unknown";
  return `[${source}] ${tail}`;
}

/** Bounded in-memory sessionId → source registry. */
export class SourceRegistry {
  #entries = new Map();

  /**
   * @param limit - maximum tracked Sessions; the oldest entry is evicted first.
   *   Eviction only costs the tag (reported as unknown), never correctness.
   */
  constructor(limit = 1000) {
    this.limit = limit;
  }

  get(sessionId) {
    return this.#entries.get(sessionId);
  }

  /** Record the creating source of one Session. */
  record(sessionId, source) {
    const existing = this.#entries.get(sessionId);
    if (existing !== undefined) this.#entries.delete(sessionId);
    this.#entries.set(sessionId, { source, createdAt: existing?.createdAt ?? Date.now() });
    while (this.#entries.size > this.limit) {
      const oldest = this.#entries.keys().next();
      if (oldest.done === true) break;
      this.#entries.delete(oldest.value);
    }
    return this.get(sessionId);
  }

  get size() {
    return this.#entries.size;
  }
}
